import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
const browser = await chromium.launch({ channel: "msedge" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("http://127.0.0.1:5173/", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Close admission enquiry" }).click();
const stage = page.getByRole("region", { name: "College event highlights" });
await stage.scrollIntoViewIfNeeded();
await page.mouse.move(1, 1);
await page.waitForTimeout(150);
await page.clock.install();
await page.getByRole("button", { name: "Pause event slideshow" }).click();
await page.getByRole("button", { name: "Play event slideshow" }).click();
await page.mouse.move(1, 1);
const active = () => page.locator(".events-pagination .is-active").innerText();
assert.equal(await active(), "01");
await page.clock.fastForward(5300);
assert.equal(await active(), "02");
await page.clock.runFor(600);
await page.getByRole("button", { name: "Pause event slideshow" }).click();
await page.clock.fastForward(12000);
assert.equal(await active(), "02");
await page.getByRole("button", { name: "Play event slideshow" }).click();
await page.mouse.move(1, 1);
await page.clock.fastForward(5300);
assert.equal(await active(), "03");
await page.clock.runFor(600);
await stage.hover({ force: true });
await page.clock.fastForward(10000);
assert.equal(await active(), "03");
await page.mouse.move(1, 1);
await page.clock.fastForward(5300);
assert.equal(await active(), "04");
await page.clock.runFor(600);
await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
await page.clock.runFor(300);
await new Promise((resolve) => setTimeout(resolve, 200));
await page.mouse.move(1, 1);
await page.clock.fastForward(12000);
assert.equal(await active(), "04");
assert.deepEqual(errors, []);
console.log(
  "PASS: automatic 5-second slide, pause/play, hover pause/resume, off-screen pause, no browser errors.",
);
await browser.close();
